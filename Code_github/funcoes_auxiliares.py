def calcular_weighted_kendall_historico(
    fronteiras_anteriores,
    parametros_utilidade,
    tipo_utilidade,
    pesos_estimados,
    pontos_estimados
):
    kendalls_historicos = []

    for fronteira in fronteiras_anteriores:

        objetivos = fronteira["objetivos"]

        utilidades_reais = UtilityFunctions.avaliar_utilidade(
            objetivos,
            parametros_utilidade,
            tipo_utilidade
        )

        utilidades_estimadas = UtilityFunctions.avaliar_utilidade_estimada(
            objetivos,
            pesos_estimados,
            pontos_estimados
        )

        ranking_real = np.argsort(np.argsort(-utilidades_reais))
        ranking_estimado = np.argsort(np.argsort(-utilidades_estimadas))

        tau, _ = weightedtau(
            ranking_real,
            ranking_estimado
        )

        kendalls_historicos.append(tau)

    if len(kendalls_historicos) == 0:
        return [], np.nan

    return kendalls_historicos, np.mean(kendalls_historicos)


