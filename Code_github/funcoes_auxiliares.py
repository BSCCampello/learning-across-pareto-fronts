def plotar_evolucao_utilidades_estatica(
    interpoladores,
    historico_modelos,
    save_path=None
):

    num_criterios = len(interpoladores)

    fig, axes = plt.subplots(
        1,
        num_criterios,
        figsize=(6 * num_criterios, 5)
    )

    if num_criterios == 1:
        axes = [axes]

    # =====================================================
    # Cores progressivas
    # =====================================================

    cmap = plt.cm.viridis

    num_iteracoes = len(historico_modelos)

    cores = [
        cmap(i / max(1, num_iteracoes - 1))
        for i in range(num_iteracoes)
    ]

    # =====================================================
    # Critérios
    # =====================================================

    for j, ax in enumerate(axes):

        # -------------------------------------------------
        # Curva real
        # -------------------------------------------------

        x_min = interpoladores[j].x.min()

        x_max = interpoladores[j].x.max()

        x_real = np.linspace(
            x_min,
            x_max,
            300
        )

        y_real = interpoladores[j](x_real)

        ax.plot(
            x_real,
            y_real,
            color="black",
            linewidth=3,
            label="Real"
        )

        # -------------------------------------------------
        # Curvas UTASTAR
        # -------------------------------------------------

        for idx, modelo_uta in enumerate(historico_modelos):

            grupo = modelo_uta.grupos_w[j]

            w_j = modelo_uta.media_geral[grupo]

            y_rec = np.concatenate([
                [0],
                np.cumsum(w_j)
            ])

            x_rec = modelo_uta.niveis[j]

            ax.plot(
                x_rec,
                y_rec,
                marker="o",
                color=cores[idx],
                alpha=0.9,
                label=f"Iter {idx+1}"
            )

        ax.set_title(
            f"Critério {j+1}"
        )

        ax.set_xlabel(
            "Desempenho"
        )

        ax.set_ylabel(
            "Utilidade"
        )

        ax.set_ylim(0, 1)

        ax.grid(True)

        ax.legend(
            fontsize=8
        )

    plt.tight_layout()

    if save_path is not None:

        plt.savefig(
            save_path,
            dpi=300,
            bbox_inches="tight"
        )

    plt.close()


