def testar_funcao_real_no_utastar(modelo_uta, interpoladores):
    w_real = []

    for j, niveis in enumerate(modelo_uta.niveis):
        valores = interpoladores[j](niveis)
        incrementos = np.diff(valores)
        w_real.extend(incrementos)

    w_real = np.array(w_real)

    print("\n===== TESTE FUNÇÃO REAL NO UTASTAR =====")
    print("Soma dos w reais projetados:", np.sum(w_real))

    violacoes = 0
    menor_folga = np.inf

    for k, m in enumerate(modelo_uta.m_w):
        diferenca = np.dot(m, w_real)

        if modelo_uta.tipos_comparacao[k] == ">":
            folga = diferenca - modelo_uta.delta
            menor_folga = min(menor_folga, folga)

            if diferenca < modelo_uta.delta:
                violacoes += 1

    print("Número de comparações:", len(modelo_uta.m_w))
    print("Número de violações:", violacoes)
    print("Menor folga:", menor_folga)

    return w_real


