def adicionar_feedback_grupo(historico, alternativas, utilidades_reais, percentual):
    k = int(np.ceil(percentual * len(alternativas)))
    indices_preferidos = np.argsort(-utilidades_reais)[:k]
    grupo_preferido = [alternativas[i] for i in indices_preferidos]

    historico.append({
        "alternativas": alternativas,
        "grupo_preferido": grupo_preferido
    })

    return grupo_preferido






def adicionar_feedback_ranking(historico, alternativas, utilidades_reais):
    ordem = np.argsort(-utilidades_reais)
    ranking = [alternativas[i] for i in ordem]

    for melhor, pior in zip(ranking[:-1], ranking[1:]):
        historico.append({
            "alternativas": [melhor, pior],
            "grupo_preferido": [melhor]
        })

    return ranking





