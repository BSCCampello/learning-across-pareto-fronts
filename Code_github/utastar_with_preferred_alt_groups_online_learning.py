    def calcular_pesos_criterios(
        self,
        w=None
    ):

        if w is None:

            w = self.media_geral

        pesos_criterios = []

        inicio = 0

        for alfa_j in self.alfa:

            fim = inicio + (
                alfa_j - 1
            )

            peso_j = np.sum(
                w[inicio:fim]
            )

            pesos_criterios.append(
                peso_j
            )

            inicio = fim

        self.pesos_criterios = np.array(
            pesos_criterios
        )